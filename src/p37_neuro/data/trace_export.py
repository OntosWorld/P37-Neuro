"""Export canonical P37 episodes as explicit, inspectable browser playback evidence.

No physics, policy, or performance claims are generated by this exporter.
"""

from __future__ import annotations

import json
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from math import isfinite
from pathlib import Path
from typing import Any

from p37_neuro.data.schema import Episode

SCHEMA_VERSION = "p37-trace-v1"
EVIDENCE_LEVELS = frozenset({"T0", "T1", "T2", "T3", "T4", "T5", "T6"})


@dataclass(frozen=True, slots=True)
class TraceProvenance:
    """Source metadata required for a public comparison claim."""

    checkpoint_sha256: str
    code_commit: str
    simulator: str
    simulator_version: str
    robot_description_sha256: str
    adapter_version: str
    seed: int
    training_membership: str
    evidence_level: str
    policy_attached: bool
    evaluation_protocol: str
    outcome: str = "unverified"

    def __post_init__(self) -> None:
        if self.evidence_level not in EVIDENCE_LEVELS:
            raise ValueError("invalid evidence level")
        if self.training_membership not in {"train", "held-out", "unknown"}:
            raise ValueError("invalid training membership")
        if not isinstance(self.seed, int) or isinstance(self.seed, bool):
            raise ValueError("seed must be an integer")
        if self.policy_attached and not self.checkpoint_sha256:
            raise ValueError("policy-attached evidence requires checkpoint hash")
        if self.outcome not in {"success", "failure", "unverified"}:
            raise ValueError("invalid outcome")
        required = (
            self.code_commit, self.simulator, self.simulator_version,
            self.robot_description_sha256, self.adapter_version, self.evaluation_protocol,
        )
        if any(not value.strip() for value in required):
            raise ValueError("incomplete provenance")


def _finite_channels(channels: Mapping[str, float], label: str) -> dict[str, float]:
    result: dict[str, float] = {}
    for key, value in channels.items():
        if not isinstance(key, str) or not key:
            raise ValueError(f"{label} has an invalid channel name")
        if not isinstance(value, (float, int)) or isinstance(value, bool) or not isfinite(value):
            raise ValueError(f"{label}.{key} must be finite")
        result[key] = float(value)
    return result


def export_episode(
    episode: Episode,
    provenance: TraceProvenance,
    *,
    label: str | None = None,
) -> dict[str, Any]:
    """Serialize **recorded** observations/actions, with no interpolation or simulation."""

    frames: list[dict[str, Any]] = []
    previous_time = -1.0
    for step in episode.steps:
        observation = step.observation
        action = step.action
        t = float(observation.timestamp_s)
        action_t = float(action.timestamp_s)
        if not isfinite(t) or t < 0 or t <= previous_time:
            raise ValueError("observation timestamps must be strictly increasing and nonnegative")
        if not isfinite(action_t) or action_t < 0:
            raise ValueError("action timestamps must be finite and nonnegative")
        if step.reward is not None and not isfinite(step.reward):
            raise ValueError("reward must be finite")
        previous_time = t
        frames.append({
            "t": t,
            "action_t": action_t,
            "joint_position": _finite_channels(observation.joint_position, "joint_position"),
            "joint_velocity": _finite_channels(observation.joint_velocity, "joint_velocity"),
            "state": _finite_channels(observation.state, "state"),
            "joint_command": _finite_channels(action.joint_commands, "joint_command"),
            "reward": step.reward,
            "terminal": step.terminal,
            "failure_code": step.failure_code,
            "intervention": step.intervention,
        })
    return {
        "schema_version": SCHEMA_VERSION,
        "episode_id": episode.episode_id,
        "embodiment_id": episode.embodiment_id,
        "task_id": episode.task_id,
        "label": label or episode.embodiment_id,
        "source": episode.source,
        "provenance": {
            "checkpoint_sha256": provenance.checkpoint_sha256,
            "code_commit": provenance.code_commit,
            "simulator": provenance.simulator,
            "simulator_version": provenance.simulator_version,
            "robot_description_sha256": provenance.robot_description_sha256,
            "adapter_version": provenance.adapter_version,
            "seed": provenance.seed,
            "training_membership": provenance.training_membership,
            "evidence_level": provenance.evidence_level,
            "policy_attached": provenance.policy_attached,
            "evaluation_protocol": provenance.evaluation_protocol,
            "outcome": provenance.outcome,
        },
        "frames": frames,
    }


def export_comparison(
    episodes: Sequence[Episode],
    provenances: Sequence[TraceProvenance],
    *,
    title: str,
) -> dict[str, Any]:
    """Create a side-by-side artifact. Shared checkpoint equality is NOT assumed."""
    if len(episodes) < 2 or len(episodes) != len(provenances):
        raise ValueError("provide at least two episodes and matching provenance records")
    if len({episode.episode_id for episode in episodes}) != len(episodes):
        raise ValueError("episode IDs must be unique")
    if len({episode.task_id for episode in episodes}) != 1:
        raise ValueError("comparison must use the same task ID")
    traces = [export_episode(ep, prov) for ep, prov in zip(episodes, provenances, strict=True)]
    return {"schema_version": SCHEMA_VERSION, "title": title, "traces": traces}


def write_comparison(path: str | Path, artifact: Mapping[str, Any]) -> None:
    """Write a strict JSON file with deterministic key ordering."""
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(
        json.dumps(artifact, indent=2, ensure_ascii=False, sort_keys=True, allow_nan=False) + "\n",
        encoding="utf-8",
    )
